"""
Admin API of QScheduler >= 0.2.1 (machines and notifiers), reached by HEAppE Management only over HTTP through an
admin proxy. No qscheduler CLI and no command inside the QScheduler container is used for it.

Admin proxy
  * One nginx container per QScheduler instance, "<name>-admin-proxy", on the local Docker host (where HEAppE and
    HEAppE Management run). It joins the HEAppE networks of the instance's assignments, so it reaches the service
    as <service_host>:<port> there - for a remote QScheduler through the tunnel that connects its Docker network to
    the local HEAppE network.
  * It forwards only the admin endpoints (/machines, /machine/{name}, /notifiers, /notifiers/{name}); everything
    else gets 404. It is published on 127.0.0.1 only (random host port), i.e. for HEAppE Management on this host.
  * ensure_proxy() creates or repairs it (networks, upstream after a restore) whenever an admin call needs it;
    sync_proxy() / remove_proxy() follow unassignments and removal of the instance.

Admin token
  * QSchedulerInstance.admin_token (encrypted in the database). Deploy stores the generated token; a Docker-based
    instance without a stored token adopts it from the container environment (docker inspect).
  * Missing or rejected token -> AdminTokenError: the UI offers to set the token by hand (e.g. copied from another
    HEAppE Management that manages the same QScheduler) or to regenerate it (recreates the container; other admin
    panels lose admin access until they get the new token).
"""
import http.client
import json
import os
import threading
import time

from django.conf import settings

from .qscheduler_core import DockerCli

PROXY_PORT = 8080
LABEL_PROXY_FOR = "qscheduler.admin-proxy-for"
LABEL_UPSTREAM = "qscheduler.admin-upstream"
PROXY_START_TIMEOUT = 15        # seconds to wait for a new proxy to accept connections
_LOCK = threading.Lock()

DOCKER_KINDS = ("managed", "local", "ssh_host")


def proxy_image():
    return getattr(settings, "QSCHEDULER_ADMIN_PROXY_IMAGE", None) or os.getenv(
        "QSCHEDULER_ADMIN_PROXY_IMAGE", "nginx:1.27-alpine")


def proxy_name(inst):
    return f"{inst.name}-admin-proxy"


# ---------------------------------------------------------------------------
# Errors
# ---------------------------------------------------------------------------

class AdminApiUnavailable(RuntimeError):
    """The admin proxy cannot be set up or does not reach the service."""


class AdminTokenError(RuntimeError):
    """The admin token is not known, not set in the service, or rejected by it."""

    MESSAGES = {
        'missing': "No admin token is stored for QScheduler '{name}'.",
        'not_set': "QScheduler '{name}' has no ADMIN_TOKEN set, so its admin API is disabled (HTTP 403).",
        'rejected': "QScheduler '{name}' rejected the stored admin token (HTTP 401): it was changed elsewhere, "
                    "e.g. regenerated by another HEAppE Management.",
    }

    def __init__(self, inst, reason):
        self.instance_id = inst.pk
        self.instance_name = inst.name
        self.reason = reason
        self.can_regenerate = inst.kind in DOCKER_KINDS
        hint = (" Set the token (Admin token...) or regenerate it." if self.can_regenerate else
                " Set the token (Admin token...) to the ADMIN_TOKEN of the service.")
        super().__init__(self.MESSAGES[reason].format(name=inst.name) + hint)

    def info(self):
        return {'instance_id': self.instance_id, 'instance_name': self.instance_name, 'reason': self.reason,
                'can_regenerate': self.can_regenerate, 'message': str(self)}


def find_admin_token_error(ex):
    """The AdminTokenError behind an exception (also when wrapped by `raise ... from` or in `except`), or None."""
    seen = set()
    while ex is not None and id(ex) not in seen:
        if isinstance(ex, AdminTokenError):
            return ex
        seen.add(id(ex))
        ex = ex.__cause__ or ex.__context__
    return None


# ---------------------------------------------------------------------------
# Proxy container
# ---------------------------------------------------------------------------

def proxy_config(host, port):
    """nginx server block: only the admin endpoints are forwarded (method, path, query, body and headers as sent)."""
    return f"""server {{
    listen {PROXY_PORT};
    resolver 127.0.0.11 valid=10s ipv6=off;
    resolver_timeout 5s;
    set $qscheduler http://{host}:{port};
    client_max_body_size 1m;
    proxy_connect_timeout 10s;
    proxy_read_timeout 120s;
    location = /__proxy_health {{ access_log off; return 200 "ok\\n"; }}
    location ~ ^/(machines|notifiers)$ {{ proxy_pass $qscheduler; }}
    location ~ ^/(machine|notifiers)/[^/]+$ {{ proxy_pass $qscheduler; }}
    location / {{ return 404; }}
}}
"""


def proxy_run_args(inst, network):
    upstream = f"{inst.service_host}:{inst.port}"
    return ["run", "-d", "--name", proxy_name(inst), "--restart", "unless-stopped",
            "--label", f"{LABEL_PROXY_FOR}={inst.name}", "--label", f"{LABEL_UPSTREAM}={upstream}",
            "--network", network, "-p", f"127.0.0.1::{PROXY_PORT}",
            "-e", f"QS_PROXY_CONF={proxy_config(inst.service_host, inst.port)}",
            proxy_image(), "sh", "-c",
            'printf "%s" "$QS_PROXY_CONF" > /etc/nginx/conf.d/default.conf && exec nginx -g "daemon off;"']


def desired_networks(inst, extra=()):
    """HEAppE networks of the instance's assignments (plus `extra`, e.g. of an assignment being created)."""
    nets = []
    for net in [a.network for a in inst.assignments.all()] + list(extra or []):
        if net and net not in nets:
            nets.append(net)
    return nets


def _host_port(info):
    for b in ((info.get("NetworkSettings") or {}).get("Ports") or {}).get(f"{PROXY_PORT}/tcp") or []:
        if b.get("HostPort"):
            return int(b["HostPort"])
    return None


def ensure_proxy(inst, log=None, extra_networks=(), docker=None):
    """Creates or repairs the admin proxy of `inst`; returns its host port on 127.0.0.1."""
    log = log or (lambda *_: None)
    nets = desired_networks(inst, extra_networks)
    if not nets:
        raise AdminApiUnavailable(
            f"The admin API of QScheduler '{inst.name}' is reached through an admin proxy in the network of an "
            f"assigned HEAppE instance: assign a HEAppE instance first.")
    docker = docker or DockerCli()
    name = proxy_name(inst)
    upstream = f"{inst.service_host}:{inst.port}"
    with _LOCK:
        info = docker.inspect(name)
        if info:
            cfg = info.get("Config") or {}
            if (cfg.get("Labels") or {}).get(LABEL_UPSTREAM) != upstream or cfg.get("Image") != proxy_image():
                log(f"Admin proxy '{name}' is outdated (upstream or image changed); recreating it.")
                docker.run(["rm", "-f", name], log)
                info = None
        if not info:
            log(f"Starting admin proxy '{name}' ({proxy_image()}) -> {upstream}, published on 127.0.0.1 only.")
            docker.run(proxy_run_args(inst, nets[0]), log)
            info = docker.inspect(name) or {}
        current = set((info.get("NetworkSettings") or {}).get("Networks") or {})
        for net in nets:
            if net not in current:
                docker.run(["network", "connect", net, name], log)
        for net in current - set(nets):
            docker.run(["network", "disconnect", net, name], log, check=False)
        if (info.get("State") or {}).get("Status") != "running":
            docker.run(["start", name], log)
            info = docker.inspect(name) or {}
        port = _host_port(info)
    if not port:
        raise AdminApiUnavailable(f"Admin proxy '{name}' has no published port.")
    return port


def remove_proxy(inst, log=None, docker=None):
    docker = docker or DockerCli()
    name = proxy_name(inst)
    with _LOCK:
        if docker.exists("container", name):
            docker.run(["rm", "-f", name], log, check=False)
            if log:
                log(f"Admin proxy '{name}' removed.")


def sync_proxy(inst, log=None):
    """After assignments changed: follow their networks, or remove the proxy when none is left."""
    try:
        if desired_networks(inst):
            if DockerCli().exists("container", proxy_name(inst)):
                ensure_proxy(inst, log)
        else:
            remove_proxy(inst, log)
    except Exception as e:
        if log:
            log(f"WARNING: could not update admin proxy '{proxy_name(inst)}': {e}")


def proxy_status(inst):
    """{'name', 'running', 'address'} of the admin proxy (no changes made)."""
    info = DockerCli().inspect(proxy_name(inst)) or {}
    running = (info.get("State") or {}).get("Status") == "running"
    port = _host_port(info) if running else None
    return {'name': proxy_name(inst), 'exists': bool(info), 'running': running,
            'address': f"127.0.0.1:{port}" if port else ""}


# ---------------------------------------------------------------------------
# Token
# ---------------------------------------------------------------------------

def container_admin_token(info):
    env = dict(e.split("=", 1) for e in ((info or {}).get("Config") or {}).get("Env") or [] if "=" in e)
    return env.get("ADMIN_TOKEN") or ""


def admin_token(inst, docker=None, log=None):
    """The stored token; a Docker-based instance without one adopts the token of its container (docker inspect)."""
    token = inst.admin_token
    if token:
        return token
    if docker is not None and inst.kind in DOCKER_KINDS and inst.container_name:
        token = container_admin_token(docker.inspect(inst.container_name))
        if token:
            inst.admin_token = token
            inst.save(update_fields=["admin_token_encrypted", "updated_at"])
            if log:
                log(f"Admin token of '{inst.name}' taken over from the container environment and stored.")
            return token
    raise AdminTokenError(inst, 'missing')


# ---------------------------------------------------------------------------
# Client
# ---------------------------------------------------------------------------

def http_request(port, method, path, token, body=None, timeout=60):
    """(status, body text) of one request to the admin proxy on 127.0.0.1:<port>."""
    data = None if body is None else json.dumps(body).encode()
    headers = {"Authorization": f"Bearer {token}", "Accept": "application/json"}
    if data is not None:
        headers["Content-Type"] = "application/json"
    conn = http.client.HTTPConnection("127.0.0.1", port, timeout=timeout)
    try:
        conn.request(method, path, body=data, headers=headers)
        resp = conn.getresponse()
        return resp.status, resp.read().decode("utf-8", "replace")
    finally:
        conn.close()


class AdminClient:
    """Admin API of one QScheduler instance through its admin proxy (created / repaired on first use)."""

    def __init__(self, inst, docker=None):
        self.inst = inst
        self.docker = docker                # docker CLI of the QScheduler host (token adoption only)
        self.extra_networks = []            # e.g. the network of an assignment being created
        self.log = None
        self._port = None

    def request(self, method, path, body=None, timeout=60):
        token = admin_token(self.inst, self.docker, self.log)
        if self._port is None:
            self._port = ensure_proxy(self.inst, self.log, self.extra_networks)
        deadline = time.time() + PROXY_START_TIMEOUT
        while True:
            try:
                status, text = http_request(self._port, method, path, token, body, timeout)
                break
            except (ConnectionRefusedError, ConnectionResetError, http.client.RemoteDisconnected):
                if time.time() > deadline:       # a just started proxy needs a moment
                    raise AdminApiUnavailable(f"Admin proxy {proxy_name(self.inst)} (127.0.0.1:{self._port}) "
                                              f"does not accept connections.")
                time.sleep(0.5)
            except OSError as e:
                raise AdminApiUnavailable(f"Admin proxy {proxy_name(self.inst)} could not be called: "
                                          f"{type(e).__name__}.")
        if status == 401:
            raise AdminTokenError(self.inst, 'rejected')
        if status == 403:
            raise AdminTokenError(self.inst, 'not_set')
        if status in (502, 504):
            raise AdminApiUnavailable(f"Admin proxy cannot reach QScheduler at {self.inst.service_host}:"
                                      f"{self.inst.port} from the HEAppE network (HTTP {status}).")
        return status, text
